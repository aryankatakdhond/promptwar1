import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { StoredEvent } from '@/types/persistence';
import { formatCurrency } from '@/lib/currency';

export function exportEventPDF(event: StoredEvent): void {
  const { profile, budget, tasks, risks } = event;
  const doc = new jsPDF();
  const margin = 14;
  let y = 18;

  doc.setFontSize(20);
  doc.setTextColor(26, 31, 46);
  doc.text('MOMENTRA', margin, y);
  y += 8;
  doc.setFontSize(11);
  doc.setTextColor(90, 97, 120);
  doc.text('Celebration Command Center', margin, y);
  y += 12;

  doc.setFontSize(16);
  doc.setTextColor(26, 31, 46);
  doc.text(profile.name, margin, y);
  y += 7;
  doc.setFontSize(10);
  doc.setTextColor(90, 97, 120);
  doc.text(`${profile.type} | ${profile.date} | ${profile.city}`, margin, y);
  y += 12;

  autoTable(doc, {
    startY: y,
    head: [['Summary', 'Value']],
    body: [
      ['Total budget', formatCurrency(profile.totalBudget, profile.currency)],
      ['Guests', `${profile.guestCount} planned | ${profile.confirmedGuestCount} confirmed`],
      ['Readiness', `${event.readinessScore.total}/100`],
      ['Open risks', String(risks.filter((risk) => !risk.isResolved).length)],
      ['Tasks', `${tasks.filter((task) => task.status === 'completed').length}/${tasks.length} complete`],
    ],
    theme: 'grid',
    headStyles: { fillColor: [196, 97, 58] },
  });

  y = (doc as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY
    ? (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10
    : y + 45;

  autoTable(doc, {
    startY: y,
    head: [['Budget category', 'Planned', 'Actual']],
    body: budget.allocations.map((allocation) => {
      const category = budget.categories.find((item) => item.id === allocation.categoryId);
      return [
        category?.name ?? allocation.categoryId,
        formatCurrency(allocation.plannedAmount, profile.currency),
        formatCurrency(allocation.actualAmount, profile.currency),
      ];
    }),
    theme: 'striped',
    headStyles: { fillColor: [26, 31, 46] },
  });

  y = (doc as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY
    ? (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10
    : y + 45;

  autoTable(doc, {
    startY: y,
    head: [['Task', 'Status', 'Due date']],
    body: tasks.slice(0, 25).map((task) => [task.title, task.status, task.dueDate]),
    theme: 'grid',
    headStyles: { fillColor: [120, 150, 107] },
  });

  doc.setFontSize(8);
  doc.setTextColor(120, 125, 140);
  doc.text('Generated by MOMENTRA. Demo vendor pricing is illustrative.', margin, 287);
  doc.save(`momentra-${profile.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'event'}.pdf`);
}
